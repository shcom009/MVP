insert into public.sense_search_form
  (search_text,search_norm,expression_family_id,sense_id,match_scope,form_type,priority,source_type,status,created_at,updated_at)
select r.search_text,regexp_replace(lower(btrim(r.search_text)),'[[:space:][:punct:]]','','g'),f.id,s.id,
       r.match_scope,r.form_type,r.priority,r.source_type,'ACTIVE',now(),now()
from _pilot_route r
join public.expression_family f on f.family_key=r.family_key
left join public.sense s on s.sense_key=r.sense_key
