create temporary table _pilot_raw_resolved on commit drop as
select distinct on (x.legacy_key) x.*,sm.id source_memo_id,cu.id candidate_unit_id,e.id expression_id
from _pilot_raw_example x
join public.source_memo sm on sm.memo_seq=x.memo_seq
join public.candidate_unit cu on cu.legacy_candidate_key=x.legacy_key
join public.expression e
  on regexp_replace(lower(coalesce(e.display_pronunciation,'')),'[^0-9a-z가-힣ぁ-んァ-ヶ一-龠]','','g')=
     regexp_replace(lower(x.pronunciation),'[^0-9a-z가-힣ぁ-んァ-ヶ一-龠]','','g')
 and e.status='ACTIVE'
order by x.legacy_key,e.id;

