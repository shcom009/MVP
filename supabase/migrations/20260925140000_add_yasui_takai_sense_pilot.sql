-- Yasui / takai pilot: route inflected searches to a lexical family, split examples by sense,
-- and connect opposites at sense level. The migration is idempotent so it can be replayed.

select pg_advisory_xact_lock(hashtext('kimtokki_yasui_takai_sense_pilot_v1'));

create table if not exists public.sense_search_form (
  id bigint generated by default as identity primary key,
  search_text text not null,
  search_norm text not null,
  expression_family_id bigint not null references public.expression_family(id) on delete cascade,
  sense_id bigint references public.sense(id) on delete cascade,
  match_scope text not null check (match_scope in ('FAMILY','SENSE')),
  form_type text not null check (form_type in ('PRONUNCIATION','MEANING','INFLECTION','PATTERN')),
  priority integer not null default 100,
  source_type text not null default 'SYSTEM_RULE' check (source_type in ('SYSTEM_RULE','USER_CONFIRMED','RAW_NOTE')),
  status text not null default 'ACTIVE' check (status in ('ACTIVE','HOLD','EXCLUDED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((match_scope='FAMILY' and sense_id is null) or (match_scope='SENSE' and sense_id is not null))
);

create unique index if not exists ux_sense_search_form_route
  on public.sense_search_form (search_norm, expression_family_id, coalesce(sense_id,0), form_type);
create index if not exists ix_sense_search_form_search_norm_active
  on public.sense_search_form (search_norm, priority desc) where status='ACTIVE';
create index if not exists ix_sense_search_form_family on public.sense_search_form (expression_family_id);
create index if not exists ix_sense_search_form_sense on public.sense_search_form (sense_id) where sense_id is not null;

create index if not exists ix_sense_relation_from_active
  on public.sense_relation (from_sense_id,display_order) where status='ACTIVE';
create index if not exists ix_sense_relation_to_active
  on public.sense_relation (to_sense_id,display_order) where status='ACTIVE' and is_bidirectional;

