create or replace function public.search_expression_sense_hub(p_query text,p_limit integer default 12)
returns table(
  family_id bigint,family_key text,display_pronunciation text,
  sense_id bigint,sense_key text,meaning_text text,usage_summary text,
  sense_order integer,match_type text,score real,examples jsonb,relations jsonb
)
language sql stable security invoker set search_path=''
as $function$
with q as (
  select regexp_replace(lower(btrim(coalesce(p_query,''))),'[[:space:][:punct:]]','','g') norm
), routes as (
  select sf.*,row_number() over (order by sf.priority desc,sf.id) route_order
  from public.sense_search_form sf,q
  where sf.status='ACTIVE' and sf.search_norm=q.norm and q.norm<>''
), targets as (
  select distinct on (s.id)
    f.id family_id,f.family_key,f.working_label display_pronunciation,
    s.id sense_id,s.sense_key,s.meaning_text,s.usage_summary,s.sense_order,
    r.form_type match_type,r.priority,r.route_order
  from routes r
  join public.expression_family f on f.id=r.expression_family_id and f.status='ACTIVE'
  join public.sense s on s.expression_family_id=f.id and s.status='ACTIVE'
   and (r.sense_id is null or s.id=r.sense_id)
  order by s.id,r.priority desc,r.route_order
), limited as (
  select * from targets order by priority desc,family_id,sense_order limit greatest(1,least(coalesce(p_limit,12),50))
)
select l.family_id,l.family_key,l.display_pronunciation,l.sense_id,l.sense_key,l.meaning_text,l.usage_summary,
       l.sense_order,l.match_type,(l.priority::real/100.0)::real score,
       coalesce(ex.examples,'[]'::jsonb),coalesce(rel.relations,'[]'::jsonb)
from limited l
left join lateral (
  select jsonb_agg(jsonb_build_object(
    'expression_id',x.expression_id,'meaning_text',x.meaning_text,
    'display_pronunciation',x.display_pronunciation,'japanese_original',x.japanese_original,
    'applicability',x.applicability
  ) order by x.expression_id) examples
  from (
    select es.expression_id,e.display_pronunciation,e.japanese_original,es.applicability,em.meaning_text
    from public.expression_sense es
    join public.expression e on e.id=es.expression_id and e.status='ACTIVE'
    join lateral (
      select m.meaning_text from public.expression_meaning m
      where m.expression_id=e.id order by m.is_primary desc,m.meaning_order,m.id limit 1
    ) em on true
    where es.sense_id=l.sense_id and es.status='ACTIVE'
    order by es.expression_id limit 30
  ) x
) ex on true
left join lateral (
  select jsonb_agg(jsonb_build_object(
    'relation_type',x.relation_type,'relation_subtype',x.relation_subtype,
    'sense_id',x.target_sense_id,'sense_key',x.target_sense_key,
    'meaning_text',x.target_meaning,'display_pronunciation',x.target_family_label
  ) order by x.display_order,x.target_sense_id) relations
  from (
    select sr.relation_type,sr.relation_subtype,sr.display_order,
           ts.id target_sense_id,ts.sense_key target_sense_key,ts.meaning_text target_meaning,
           tf.working_label target_family_label
    from public.sense_relation sr
    join public.sense ts on ts.id=sr.to_sense_id and ts.status='ACTIVE'
    join public.expression_family tf on tf.id=ts.expression_family_id and tf.status='ACTIVE'
    where sr.from_sense_id=l.sense_id and sr.status='ACTIVE'
    union all
    select sr.relation_type,sr.relation_subtype,sr.display_order,
           ts.id,ts.sense_key,ts.meaning_text,tf.working_label
    from public.sense_relation sr
    join public.sense ts on ts.id=sr.from_sense_id and ts.status='ACTIVE'
    join public.expression_family tf on tf.id=ts.expression_family_id and tf.status='ACTIVE'
    where sr.to_sense_id=l.sense_id and sr.status='ACTIVE' and sr.is_bidirectional
  ) x
) rel on true
order by l.priority desc,l.family_id,l.sense_order;
$function$;

