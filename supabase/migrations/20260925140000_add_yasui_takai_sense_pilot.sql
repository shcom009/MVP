set search_text=excluded.search_text,match_scope=excluded.match_scope,priority=excluded.priority,
    source_type=excluded.source_type,status='ACTIVE',updated_at=now();

insert into public.sense_relation
  (from_sense_id,to_sense_id,relation_type,relation_subtype,is_bidirectional,display_order,status,verification_status,created_at,updated_at)
select least(a.id,b.id),greatest(a.id,b.id),v.relation_type,v.relation_subtype,true,v.display_order,'ACTIVE','VERIFIED',now(),now()
from (values
  ('S_YASUI_PRICE','S_TAKAI_PRICE','ANTONYM','PRICE',1),
  ('S_YASUI_EASY','S_YASUI_SUFFIX_EASY','RELATED','EASY_EXPRESSION',2),
  ('S_YASUI_EASY','S_TAYASUI_EASY','RELATED','EASY_EXPRESSION',3)
) v(from_key,to_key,relation_type,relation_subtype,display_order)
join public.sense a on a.sense_key=v.from_key
join public.sense b on b.sense_key=v.to_key
where not exists (
  select 1 from public.sense_relation sr
  where sr.from_sense_id=least(a.id,b.id) and sr.to_sense_id=greatest(a.id,b.id)
    and sr.relation_type=v.relation_type and coalesce(sr.relation_subtype,'')=coalesce(v.relation_subtype,'')
);

update public.sense_relation sr
set is_bidirectional=true,display_order=v.display_order,status='ACTIVE',verification_status='VERIFIED',updated_at=now()
from (values
  ('S_YASUI_PRICE','S_TAKAI_PRICE','ANTONYM','PRICE',1),
  ('S_YASUI_EASY','S_YASUI_SUFFIX_EASY','RELATED','EASY_EXPRESSION',2),
  ('S_YASUI_EASY','S_TAYASUI_EASY','RELATED','EASY_EXPRESSION',3)
) v(from_key,to_key,relation_type,relation_subtype,display_order)
join public.sense a on a.sense_key=v.from_key
join public.sense b on b.sense_key=v.to_key
where sr.from_sense_id=least(a.id,b.id) and sr.to_sense_id=greatest(a.id,b.id)
  and sr.relation_type=v.relation_type and coalesce(sr.relation_subtype,'')=coalesce(v.relation_subtype,'');

